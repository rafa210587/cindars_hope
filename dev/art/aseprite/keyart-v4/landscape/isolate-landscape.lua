local function inside(x,y,p)
 local hit=false;local j=#p-1
 for i=1,#p,2 do
  local xi,yi=p[i],p[i+1];local xj,yj=p[j],p[j+1]
  if ((yi>y)~=(yj>y)) and (x<(xj-xi)*(y-yi)/(yj-yi)+xi) then hit=not hit end
  j=i
 end
 return hit
end
